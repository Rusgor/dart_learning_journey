/// Завдання 1: Математичні оператори
void task1() {
  final width = 18.4;
  final height = 30.9;

  final area = width * height;
  final perimeter = 2 * (width + height);

  print('Area: $area');
  print('Perimeter: $perimeter');

  final squares = area ~/ 1;
  print('Full 1x1 squares: $squares');
}
